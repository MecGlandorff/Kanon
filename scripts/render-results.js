#!/usr/bin/env node

import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { atomicWriteContained } from "../src/persistence/safe-fs.js";
import { resolveContainedPath } from "../src/path-security.js";
import { safeTerminalText } from "../src/trust.js";

const repoRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  ".."
);
const options = parseArgs(process.argv.slice(2));
const input = selectedFile(options.input);
if (input.stat.size > 16 * 1024 * 1024) {
  throw new Error("Raw evaluation report exceeds its 16 MiB render limit.");
}
const bytes = fs.readFileSync(input.path);
const run = JSON.parse(bytes.toString("utf8"));
validateRun(run);
const markdown = render(run, {
  input: path.relative(repoRoot, input.path).replaceAll("\\", "/"),
  sha256: crypto.createHash("sha256").update(bytes).digest("hex")
});
const output = path.resolve(options.output);
const relative = path.relative(repoRoot, output).replaceAll("\\", "/");
if (
  !relative ||
  relative === ".." ||
  relative.startsWith("../") ||
  path.isAbsolute(relative)
) {
  throw new Error("RESULTS output must stay inside the repository.");
}
atomicWriteContained(repoRoot, relative, markdown);
process.stdout.write(`Rendered ${relative} from ${options.input}\n`);

function render(run, source) {
  const summary = run.summary;
  const lines = [
    "<!-- Generated by scripts/render-results.js; do not hand-edit. -->",
    "",
    "# Development corpus results",
    "",
    "This is an in-sample frozen compatibility sample, not a population-level capability estimate.",
    "",
    `Raw report: \`${safe(source.input)}\``,
    "",
    `Raw report SHA-256: \`${source.sha256}\``,
    "",
    `Generated: \`${safe(run.generated_at)}\``,
    "",
    `Candidate: \`${safe(run.candidate?.commit || "unresolved")}\` at \`${safe(run.candidate?.version || "unknown")}\` (worktree clean: \`${String(run.candidate?.worktree_clean ?? "unknown")}\`)`,
    "",
    `Analyzer: \`${safe(run.analyzer.version)}\` (${safe(run.analyzer.source)})`,
    "",
    `Corpus SHA-256: \`${safe(run.corpus.manifest_sha256)}\``,
    "",
    "## Gate",
    "",
    `Development thresholds: **${summary.passed ? "PASS" : "FAIL"}**`,
    "",
    `Cases: ${summary.case_count}/${summary.expected_case_count}; analysis errors: ${summary.analysis_error_count}; incomplete scans: ${summary.incomplete_scan_count}.`,
    "",
    "| Measure | Precision | Recall | 95% precision interval | 95% recall interval | TP | FP | FN |",
    "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    metricRow("Overall", summary.totals),
    ...Object.entries(summary.dimensions).map(([name, score]) =>
      metricRow(name, score)
    ),
    "",
    `Weighted error per case: ${number(summary.totals.weighted_error_per_case)}.`,
    "",
    `Case-average precision/recall: ${rate(summary.case_average.precision)} / ${rate(summary.case_average.recall)}.`,
    "",
    `Macro over categories: ${rate(summary.macro_over_category.precision)} / ${rate(summary.macro_over_category.recall)}.`,
    "",
    `Macro over dimensions: ${rate(summary.macro_over_dimension.precision)} / ${rate(summary.macro_over_dimension.recall)}.`,
    "",
    "## Categories",
    "",
    "| Category | Cases | Precision | Recall | 95% precision interval | 95% recall interval |",
    "| --- | ---: | ---: | ---: | ---: | ---: |",
    ...Object.entries(summary.categories).map(([name, score]) =>
      `| ${safe(name)} | ${score.case_count} | ${rate(score.precision)} | ${rate(score.recall)} | ${interval(score.precision_interval)} | ${interval(score.recall_interval)} |`
    ),
    "",
    "## Coverage",
    "",
    "| Dimension | Prediction coverage | Abstentions |",
    "| --- | ---: | ---: |",
    ...Object.keys(summary.prediction_coverage).map((name) =>
      `| ${safe(name)} | ${rate(summary.prediction_coverage[name])} | ${summary.abstentions[name]} |`
    ),
    "",
    "## Gate reasons",
    ""
  ];
  if (summary.failures.length) {
    lines.push(
      ...summary.failures.map((failure) => `- ${safe(failure)}`)
    );
  } else {
    lines.push("- Every predeclared development gate passed.");
  }
  lines.push(
    "",
    "## Stable-release status",
    "",
    "No held-out capability estimate is claimed by this development report. Stable release still requires a separately sealed, independently labeled holdout evaluated exactly once against the exact packed artifact.",
    ""
  );
  return lines.join("\n");
}

function metricRow(name, score) {
  return (
    `| ${safe(name)} | ${rate(score.precision)} | ` +
    `${rate(score.recall)} | ${interval(score.precision_interval)} | ` +
    `${interval(score.recall_interval)} | ${score.tp} | ${score.fp} | ` +
    `${score.fn} |`
  );
}

function validateRun(run) {
  if (
    !run ||
    run.corpus?.evaluation_role !== "development" ||
    !run.summary ||
    !Array.isArray(run.results) ||
    run.results.length !== run.summary.case_count
  ) {
    throw new Error("Expected a complete raw development evaluation report.");
  }
}

function selectedFile(value) {
  const resolved = path.resolve(value);
  const parent = fs.realpathSync(path.dirname(resolved));
  const file = resolveContainedPath(parent, path.basename(resolved), {
    type: "file"
  });
  if (!file.ok) {
    throw new Error(`Unsafe raw report: ${file.reason}`);
  }
  return file;
}

function parseArgs(argv) {
  const output = {
    input: null,
    output: path.join(repoRoot, "eval", "RESULTS.md")
  };
  for (let index = 0; index < argv.length; index += 1) {
    if (argv[index] === "--input") {
      output.input = argv[++index];
    } else if (argv[index] === "--output") {
      output.output = argv[++index];
    } else {
      throw new Error(`Unknown results option: ${argv[index]}`);
    }
  }
  if (!output.input) {
    throw new Error("--input raw-report.json is required.");
  }
  return output;
}

function safe(value) {
  return safeTerminalText(value).replaceAll("|", "\\|");
}

function rate(value) {
  return `${(value * 100).toFixed(1)}%`;
}

function interval(value) {
  return `${rate(value.lower)}–${rate(value.upper)}`;
}

function number(value) {
  return Number.isFinite(value) ? value.toFixed(2) : "∞";
}
